import { Controller } from "@hotwired/stimulus"

/*
  This controller manages executable code blocks generated by the LLM.
  Blocks are intercepted by the customized markdown helper and duplicated into a syntax-highlighted block, and 
  a hidden pre block for raw code.
*/
export default class extends Controller {
  static targets = ["highlightedCode", "rawCode", "actionsContainer"]
  static values = {
    renderTarget: String, // 'chalkboard' or 'inline'
    autoRun: Boolean,     // true or false
    hidden: Boolean       // true or false
  }

  connect() {
    //console.log("Code Executor connected", this.element);
    //console.log("Config:", this.renderTargetValue, this.autoRunValue, this.hiddenValue);

    const rawCode = this.rawCodeTarget.textContent;
    const actionsContainer = this.actionsContainerTarget;

    // Create and append buttons
    const toggleBtn = this.createToggleButton();
    actionsContainer.appendChild(toggleBtn);

    const runBtn = this.createRunButton(rawCode);
    actionsContainer.appendChild(runBtn);

    const archiveBtn = this.createArchiveButton(rawCode);
    actionsContainer.appendChild(archiveBtn);

    // Create inline output div if needed (initially hidden)
    if (this.renderTargetValue === 'inline') {
      const outputDiv = this.createOutputDiv();
      this.element.appendChild(outputDiv); // Append to the main wrapper
    }

    // Handle initial state
    if (this.hiddenValue) {
      this.highlightedCodeTarget.style.display = 'none';
      toggleBtn.textContent = "Show Code";
    } else {
      this.highlightedCodeTarget.style.display = 'block';
      toggleBtn.textContent = "Hide Code";
    }

    if (this.autoRunValue) {
      this.executeCode(rawCode, this.renderTargetValue);
    }
  }

  createToggleButton() {
    const toggleBtn = document.createElement("button");
    // Initial text content is set in connect() based on hiddenValue
    toggleBtn.className = "px-3 py-1 text-sm font-sans text-gray-900 dark:text-gray-100 bg-sky-200 dark:bg-sky-800 border border-sky-300 dark:border-sky-600 hover:border-sky-500 dark:hover:border-sky-400 rounded"; // Added rounded
    toggleBtn.addEventListener("click", () => {
      const isHidden = this.highlightedCodeTarget.style.display === 'none';
      this.highlightedCodeTarget.style.display = isHidden ? 'block' : 'none';
      toggleBtn.textContent = isHidden ? "Hide Code" : "Show Code";
    });
    return toggleBtn;
  }

  createRunButton(rawCode) {
    const button = document.createElement("button");
    button.textContent = "Run";
    button.className = "px-3 py-1 ml-2 text-sm font-sans text-gray-900 dark:text-gray-100 bg-green-200 dark:bg-green-800 border border-green-300 dark:border-green-600 hover:border-green-500 dark:hover:border-green-400 rounded"; // Added rounded
    button.addEventListener("click", () => this.executeCode(rawCode, this.renderTargetValue));
    return button;
  }

  createArchiveButton(rawCode) {
    const button = document.createElement("button");
    button.textContent = "Archive";
    button.className = "px-3 py-1 text-sm font-sans ml-2 text-gray-900 dark:text-gray-100 bg-stone-300 dark:bg-stone-700 border border-stone-400 dark:border-stone-500 hover:border-stone-600 dark:hover:border-stone-400 rounded"; // Added rounded
    button.addEventListener("click", () => this.archiveApplet(rawCode));
    return button;
  }

  createOutputDiv() {
    const output = document.createElement("div");
    // Add data target for potential future use or easier selection
    output.setAttribute("data-code-executor-target", "inlineOutput");
    output.className = "mt-2 p-2 bg-stone-100 dark:bg-stone-900 text-black dark:text-white rounded-sm border border-stone-300 dark:border-stone-600"; // Added border and dark mode text
    output.style.display = "none"; // Initially hidden
    return output;
  }

  executeCode(rawCode, renderTarget) {
    //console.log(`Executing code (target: ${renderTarget})`);
    const output = this.getOutputElement(renderTarget);
    if (!output) return;

    output.innerHTML = ''; // Clear previous content
    output.style.display = 'block'; // Make sure output area is visible

    const iframe = this.createSandboxedIframe(renderTarget);
    output.appendChild(iframe);

    const iframeContent = this.prepareIframeContent(rawCode);
    iframe.srcdoc = iframeContent;
  }

  // Helper method to get the output element based on the render target
  getOutputElement(renderTarget) {
    if (renderTarget === 'chalkboard') {
      // Find the global chalkboard element by its ID
      const output = document.getElementById('chalkboard');
      if (!output) {
        console.error("Chalkboard element with id='chalkboard' not found");
        return null;
      }
      // Ensure chalkboard is visible (might be handled by other controllers, but good practice)
      // output.closest('[data-controller="tabs"]')?.showTab('chalkboard'); // Example if tabs are used
      output.style.display = "block"; // Simple show
      output.innerHTML = ""; // Clear it
      return output;
    } else { // 'inline'
      // Find the inline output div within this controller's element
      const output = this.element.querySelector('[data-code-executor-target="inlineOutput"]');
      if (!output) {
        console.error("Inline output element not found within code block wrapper.");
        return null;
      }
      output.style.display = "block"; // Show it
      output.innerHTML = ""; // Clear it
      return output;
    }
  }

  createSandboxedIframe(renderTarget) {
    const iframe = document.createElement('iframe');
    iframe.sandbox = 'allow-scripts allow-modals allow-pointer-lock allow-popups allow-presentation allow-forms allow-downloads';
    iframe.allow = [
      'fullscreen',
      'accelerometer *',
      'encrypted-media *',
      'gyroscope *',
      'gamepad *',
      'midi *',
      'clipboard-write *',
      'web-share *',
      'local-fonts *',
      'xr-spatial-tracking *'
    ].join('; ');
    iframe.style.width = '100%';
    iframe.style.height = renderTarget === 'chalkboard' ? '100%' : '400px'; // Use 100% height for chalkboard
    iframe.style.border = '1px solid #ccc'; // Basic border
    iframe.style.backgroundColor = 'white'; // Ensure iframe bg is white for contrast
    return iframe;
  }

  prepareIframeContent(code) {
    // Basic HTML structure for the iframe content
    // Includes a simple console override to display logs/errors within the iframe
    const codeLiteral = JSON.stringify(code);
    return `
      <!DOCTYPE html>
      <html>
      <head>
        <script src="https://cdn.jsdelivr.net/npm/@tailwindcss/browser@4"></script>
        <style>
          @import url('https://fonts.googleapis.com/css2?family=Inter:ital,opsz,wght@0,14..32,100..900;1,14..32,100..900&family=Merriweather:ital,opsz,wght@0,18..144,300..900;1,18..144,300..900&display=swap');
          body { margin: 0; padding: 10px; font-family: "Inter", "Segoe UI", Optima, Futura, "Gill Sans MT", "Gill Sans", sans-serif; color: #333; }
          .error { color: red; font-weight: bold; }
          #sandbox { min-height: 50px; } /* Ensure sandbox div has some height */
        </style>
        <style type="text/tailwindcss">      
          @theme { --font-sans: "InterVariable", sans-serif; --font-serif: "Merriweather", serif; }    
        </style>
        <script type="importmap">
          {
            "imports": {
              "react": "https://esm.sh/react",
              "react/": "https://esm.sh/react/",
              "react-dom/": "https://esm.sh/react-dom/",
              "p5": "https://esm.sh/p5?standalone",  
              "three": "https://esm.sh/three"
            }
          }
        </script>
      </head>
      <body>
        <div id="sandbox"></div>
        <script type="module">
          // Simple console override
          const console = {
            log: (...args) => {
              const logElement = document.createElement('div');
              logElement.textContent = args.map(arg => typeof arg === 'object' ? JSON.stringify(arg) : arg).join(' ');
              sandbox.appendChild(logElement);
            },
            error: (...args) => {
              const errorElement = document.createElement('div');
              errorElement.textContent = 'Error: ' + args.map(arg => arg instanceof Error ? arg.message : (typeof arg === 'object' ? JSON.stringify(arg) : arg)).join(' ');
              errorElement.className = 'error';
              sandbox.appendChild(errorElement);
            }
          };

          const code = ${codeLiteral};
          const moduleCode = JSON.stringify(code);
          const blob = new Blob([JSON.parse(moduleCode)], { type: 'text/javascript' });
          const moduleUrl = URL.createObjectURL(blob);
          await import(moduleUrl).catch(error => {
            console.error(error);
          }).finally(() => {
            URL.revokeObjectURL(moduleUrl);
          });
        </script>
      </body>
      </html>
    `;
  }

  archiveApplet(rawCode) {
    // Use the rawCode passed directly
    const title = prompt("Enter a name for this applet:");
    if (!title) return; // User cancelled

    const csrfToken = document.querySelector('meta[name="csrf-token"]')?.getAttribute('content');
    if (!csrfToken) {
        console.error("CSRF token not found");
        alert('Error: CSRF token missing. Cannot archive applet.');
        return;
    }

    fetch('/applets', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'X-CSRF-Token': csrfToken
      },
      body: JSON.stringify({ applet: { title: title, code: rawCode } })
    })
    .then(response => {
      if (response.ok) {
        alert('Applet archived successfully!');
        // Optionally: Disable archive button or change its appearance
      } else {
        response.text().then(text => {
           console.error('Failed to archive applet:', response.status, text);
           alert(`Failed to archive applet. Status: ${response.status}`);
        });
      }
    })
    .catch(error => {
      console.error('Error archiving applet:', error);
      alert('An error occurred while archiving the applet.');
    });
  }
}