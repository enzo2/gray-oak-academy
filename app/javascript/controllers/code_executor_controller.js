import { Controller } from "@hotwired/stimulus"
import { attachAppletResultChannel } from "applet_result_channel"
import {
  appletFrameBackgroundColor,
  appletFrameBorderColor,
  attachAppletThemeRequestResponder,
  currentAppletTheme,
  syncAppletIframeTheme
} from "applet_theme"

/*
  This controller manages executable code blocks generated by the LLM.
  Blocks are intercepted by the customized markdown helper and duplicated into a syntax-highlighted block, and 
  a hidden pre block for raw code.
*/
export default class extends Controller {
  static targets = [
    "highlightedCode",
    "rawCode",
    "actionsContainer",
    "saveForm",
    "titleInput",
    "codeInput",
    "inlineOutput"
  ]
  static values = {
    renderTarget: String, // 'chalkboard' or 'inline'
    autoRun: Boolean,     // true or false
    hidden: Boolean       // true or false
  }

  connect() {
    //console.log("Code Executor connected", this.element);
    //console.log("Config:", this.renderTargetValue, this.autoRunValue, this.hiddenValue);

    this.pendingAutoRun = false;
    this.pendingAutoRunRawCode = null;
    this.pendingAutoRunRenderTarget = null;
    this.pendingShellTemplateTimer = null;
    this.messageId = this.resolveMessageId();
    this.boundHandleCompletionFinished ||= this.handleCompletionFinished.bind(this);
    this.boundHandleThemeChange ||= this.handleThemeChange.bind(this);
    document.addEventListener("llm-completion-finished", this.boundHandleCompletionFinished);
    window.addEventListener("goa:theme-change", this.boundHandleThemeChange);
    this._detachThemeRequestResponder = attachAppletThemeRequestResponder(() => this._inlineIframe ? [this._inlineIframe] : []);

    const rawCode = this.rawCodeTarget.textContent;
    const actionsContainer = this.actionsContainerTarget;

    // Create and append buttons
    const toggleBtn = this.createToggleButton();
    actionsContainer.appendChild(toggleBtn);

    const runBtn = this.createRunButton(rawCode);
    actionsContainer.appendChild(runBtn);

    const archiveBtn = this.createArchiveButton(rawCode);
    actionsContainer.appendChild(archiveBtn);


    // Handle initial state
    if (this.hiddenValue) {
      this.highlightedCodeTarget.style.display = 'none';
      this.setButtonLabel(toggleBtn, "Show Code");
    } else {
      this.highlightedCodeTarget.style.display = 'block';
      this.setButtonLabel(toggleBtn, "Hide Code");
    }

    if (this.autoRunValue) this.scheduleAutoRun(rawCode, this.renderTargetValue);
  }

  disconnect() {
    document.removeEventListener("llm-completion-finished", this.boundHandleCompletionFinished);
    window.removeEventListener("goa:theme-change", this.boundHandleThemeChange);
    this.clearPendingAutoRunTimer();
    this.clearPendingShellTemplateTimer();
    if (this._inlineResultDetach) {
      this._inlineResultDetach();
      this._inlineResultDetach = null;
    }
    this._detachThemeRequestResponder?.();
    this._inlineIframe = null;
  }

  resolveConversationId() {
    const convEl = this.element.closest("[data-controller~='conversation']");
    if (!convEl) return null;
    const valueEl = convEl.querySelector("[data-new-message-conversation-id-value]");
    const fromValue = valueEl?.dataset.newMessageConversationIdValue;
    if (fromValue) return fromValue;
    const match = (convEl.id || "").match(/(\d+)$/);
    return match ? match[1] : null;
  }

  _createButton(text, className, onClick, iconName = null) {
    const button = document.createElement("button")
    button.type = "button"
    button.className = `inline-flex items-center gap-1.5 ${className}`

    if (iconName) {
      const icon = document.createElement("sl-icon")
      icon.name = iconName
      icon.className = "text-sm"
      button.appendChild(icon)
    }

    const label = document.createElement("span")
    label.textContent = text
    button.appendChild(label)

    button.addEventListener("click", onClick)
    return button
  }

  setButtonLabel(button, text) {
    const label = button.querySelector("span")
    if (label) {
      label.textContent = text
    } else {
      button.textContent = text
    }
  }

  createToggleButton() {
    const btn = this._createButton(
      // Initial text is set in connect()
      "",
      "px-2 py-0.5 text-xs font-sans rounded-sm text-stone-600 dark:text-stone-300 bg-white dark:bg-stone-800 border border-stone-300 dark:border-stone-600 hover:bg-stone-100 dark:hover:bg-stone-700",
      () => {
        const isHidden = this.highlightedCodeTarget.style.display === 'none'
        this.highlightedCodeTarget.style.display = isHidden ? 'block' : 'none'
        this.setButtonLabel(btn, isHidden ? "Hide Code" : "Show Code")
      },
      "code-slash"
    )
    return btn
  }

  createRunButton(rawCode) {
    return this._createButton(
      "Run",
      "px-2 py-0.5 text-xs font-sans rounded-sm text-success-700 dark:text-success-400 bg-white dark:bg-stone-800 border border-success-600 dark:border-success-500 hover:bg-success-50 dark:hover:bg-success-950",
      () => this.executeCode(rawCode, this.renderTargetValue, { manual: true, autoRun: false }),
      "play-fill"
    )
  }

  createArchiveButton(rawCode) {
    return this._createButton(
      "Save",
      "px-2 py-0.5 text-xs font-sans rounded-sm text-stone-600 dark:text-stone-300 bg-white dark:bg-stone-800 border border-stone-300 dark:border-stone-600 hover:bg-stone-100 dark:hover:bg-stone-700",
      () => this.archiveApplet(rawCode),
      "archive"
    )
  }

  executeCode(rawCode, renderTarget, options = {}) {
    if (renderTarget === "chalkboard") {
      this.executeChalkboardCode(rawCode, options);
      return;
    }

    const output = this.getOutputElement(renderTarget);
    if (!output) return;

    output.innerHTML = ''; // Clear previous content
    output.style.display = 'block'; // Make sure output area is visible

    const iframe = this.createSandboxedIframe(renderTarget);
    this._inlineIframe = iframe;
    output.appendChild(iframe);

    const iframeContent = this.prepareIframeContent(rawCode);
    iframe.srcdoc = iframeContent;

    if (this._inlineResultDetach) this._inlineResultDetach();
    this._inlineResultDetach = attachAppletResultChannel(iframe, {
      conversationId: this.resolveConversationId(),
      messageId: this.messageId,
      title: this.buildGeneratedAppletTitle(),
      appletKey: this.buildInlineAppletKey(rawCode)
    });
  }

  scheduleAutoRun(rawCode, renderTarget) {
    // If this block is in a streamed assistant message, defer until stream completion
    // (or after a short idle fallback) to avoid repeated auto-runs on each content replace.
    if (this.shouldDeferAutoRun()) {
      this.pendingAutoRun = true;
      this.pendingAutoRunRawCode = rawCode;
      this.pendingAutoRunRenderTarget = renderTarget;
      this.queueDeferredAutoRun();
      return;
    }

    this.executeCodeWhenShellReady(rawCode, renderTarget, { manual: false, autoRun: true });
  }

  shouldDeferAutoRun() {
    if (!this.messageId) return false;
    if (this.messageCompletionRegistry().has(this.messageId)) return false;
    if (!this.isLatestAssistantMessage(this.messageId)) return false;

    return true;
  }

  queueDeferredAutoRun() {
    this.clearPendingAutoRunTimer();
    this.pendingAutoRunTimer = setTimeout(() => this.runPendingAutoRun(), 700);
  }

  clearPendingAutoRunTimer() {
    if (this.pendingAutoRunTimer) {
      clearTimeout(this.pendingAutoRunTimer);
      this.pendingAutoRunTimer = null;
    }
  }

  runPendingAutoRun() {
    if (!this.pendingAutoRun || !this.pendingAutoRunRawCode || !this.pendingAutoRunRenderTarget) return;

    this.pendingAutoRun = false;
    const code = this.pendingAutoRunRawCode;
    const renderTarget = this.pendingAutoRunRenderTarget;
    this.pendingAutoRunRawCode = null;
    this.pendingAutoRunRenderTarget = null;
    this.executeCodeWhenShellReady(code, renderTarget, { manual: false, autoRun: true });
  }

  executeCodeWhenShellReady(rawCode, renderTarget, options = {}, attempt = 0) {
    if (this.hasAppletShellTemplate()) {
      this.executeCode(rawCode, renderTarget, options);
      return;
    }

    if (attempt >= 40) {
      this.executeCode(rawCode, renderTarget, options);
      return;
    }

    this.clearPendingShellTemplateTimer();
    this.pendingShellTemplateTimer = setTimeout(() => {
      this.pendingShellTemplateTimer = null;
      this.executeCodeWhenShellReady(rawCode, renderTarget, options, attempt + 1);
    }, 50);
  }

  clearPendingShellTemplateTimer() {
    if (this.pendingShellTemplateTimer) {
      clearTimeout(this.pendingShellTemplateTimer);
      this.pendingShellTemplateTimer = null;
    }
  }

  handleCompletionFinished(event) {
    const completedMessageId = event.detail?.message_id?.toString();
    if (!completedMessageId) return;

    this.messageCompletionRegistry().add(completedMessageId);

    if (this.messageId === completedMessageId) {
      this.runPendingAutoRun();
    }
  }

  messageCompletionRegistry() {
    if (!window.__goaCompletedAssistantMessageIds) {
      window.__goaCompletedAssistantMessageIds = new Set();
    }
    return window.__goaCompletedAssistantMessageIds;
  }

  resolveMessageId() {
    const messageElement = this.element.closest("[data-message-id-param]");
    return messageElement?.dataset.messageIdParam || null;
  }

  isLatestAssistantMessage(messageId) {
    const messageElement = this.element.closest("[data-message-id-param]");
    if (!messageElement) return false;

    const conversationElement = messageElement.closest("[data-controller~='conversation']");
    if (!conversationElement) return false;

    const assistantMessages = conversationElement.querySelectorAll("[data-tts-stream-target='assistantMessage'][data-message-id-param]");
    const latestAssistant = assistantMessages[assistantMessages.length - 1];
    if (!latestAssistant) return false;

    return latestAssistant.dataset.messageIdParam === messageId;
  }

  executeChalkboardCode(rawCode, options = {}) {
    const autoRun = !!options.autoRun;
    const appletKey = autoRun ? this.buildAutoRunAppletKey(rawCode) : `jit_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;

    // During streaming, message content is re-rendered repeatedly.
    // Auto-run applets should register only once per message block + code payload.
    if (autoRun && this.hasAutoRunExecuted(appletKey)) {
      return;
    }

    const iframeContent = this.prepareIframeContentResult(rawCode);
    const appletTitle = this.buildGeneratedAppletTitle();
    this.dispatchChalkboardAppletRegistration({
      event_type: "register_applet",
      source: "jit",
      key: appletKey,
      applet_id: null,
      title: appletTitle,
      launch_url: null,
      embed_src: null,
      embed_srcdoc: iframeContent.html,
      shareable: false,
      share_url: null,
      focus: true,
      auto_open_in_board: true,
      conversation_id: this.resolveConversationId(),
      message_id: this.messageId
    });

    if (autoRun && iframeContent.shellFound) {
      this.markAutoRunExecuted(appletKey);
    }
  }

  buildGeneratedAppletTitle() {
    const now = new Date();
    const time = now.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
    return `Generated Applet ${time}`;
  }

  dispatchChalkboardAppletRegistration(payload) {
    window.dispatchEvent(new CustomEvent("chalkboard:register-applet", { detail: payload }));
  }

  buildAutoRunAppletKey(rawCode) {
    const messageElement = this.element.closest("[data-message-id-param]");
    const messageId = messageElement?.dataset.messageIdParam || "standalone";
    const blockIndex = this.blockIndexWithinMessage(messageElement);
    const codeHash = this.hashString(rawCode);

    return `jit_auto_${messageId}_${blockIndex}_${codeHash}`;
  }

  buildInlineAppletKey(rawCode) {
    const messageElement = this.element.closest("[data-message-id-param]");
    const messageId = messageElement?.dataset.messageIdParam || "standalone";
    const blockIndex = this.blockIndexWithinMessage(messageElement);
    const codeHash = this.hashString(rawCode);

    return `inline_${messageId}_${blockIndex}_${codeHash}`;
  }

  blockIndexWithinMessage(messageElement) {
    if (!messageElement) return 0;

    const executableBlocks = Array.from(messageElement.querySelectorAll("[data-controller~='code-executor']"));
    const idx = executableBlocks.indexOf(this.element);
    return idx >= 0 ? idx : 0;
  }

  autoRunRegistry() {
    if (!window.__goaAutoRunAppletKeys) {
      window.__goaAutoRunAppletKeys = new Set();
    }
    return window.__goaAutoRunAppletKeys;
  }

  hasAutoRunExecuted(appletKey) {
    return this.autoRunRegistry().has(appletKey);
  }

  markAutoRunExecuted(appletKey) {
    this.autoRunRegistry().add(appletKey);
  }

  hashString(value) {
    // Simple stable 32-bit hash for deterministic applet keys.
    let hash = 0;
    for (let i = 0; i < value.length; i += 1) {
      hash = ((hash << 5) - hash) + value.charCodeAt(i);
      hash |= 0;
    }
    return Math.abs(hash).toString(36);
  }

  // Helper method to get the applet output element based on the render target
  getOutputElement(renderTarget) {
    if (!this.hasInlineOutputTarget) {
      console.error("Inline output element not found within code block wrapper.");
      return null;
    }
    const output = this.inlineOutputTarget;
    output.style.display = "block";
    output.innerHTML = ""; // Clear previous content
    return output;
  }

  createSandboxedIframe(renderTarget) {
    const iframe = document.createElement('iframe');
    iframe.sandbox = 'allow-scripts allow-modals allow-pointer-lock allow-popups allow-presentation allow-forms allow-downloads';
    iframe.allow = [
      'fullscreen',
      'accelerometer *',
      'encrypted-media *',
      'gyroscope *',
      'magnetometer *',
      'gamepad *',
      'midi *',
      'clipboard-write *',
      'local-fonts *',
      'xr-spatial-tracking *'
    ].join('; ');
    iframe.style.width = '100%';
    iframe.style.height = renderTarget === 'chalkboard' ? '100%' : '400px'; // Use 100% height for chalkboard
    iframe.style.border = `1px solid ${appletFrameBorderColor()}`;
    iframe.style.backgroundColor = appletFrameBackgroundColor();
    iframe.dataset.appletThemeBorder = "true";
    return iframe;
  }

  handleThemeChange() {
    if (this._inlineIframe) syncAppletIframeTheme(this._inlineIframe, { border: true });
  }

  // Builds iframe content from the shared ERB-rendered shell template.
  prepareIframeContent(code) {
    return this.prepareIframeContentResult(code).html;
  }

  prepareIframeContentResult(code) {
    // Escape any </script> tags in the code to prevent terminating the script early
    const codeLiteral = JSON.stringify(code).replace(/<\/script>/g, '<\\/script>');
    const meta = document.querySelector("meta[name='csp-nonce']");
    const nonce = meta ? meta.content : "";
    const theme = currentAppletTheme();
    const htmlClass = theme === "dark" ? "dark" : "";
    const shellTemplate = this.appletShellTemplate();

    if (!shellTemplate) {
      console.error("Applet shell template not found.");
      return { html: this.prepareMissingShellContent(theme), shellFound: false };
    }

    const html = shellTemplate
      .replaceAll("\"__GOA_APPLET_THEME_JSON__\"", JSON.stringify(theme))
      .replaceAll("__GOA_APPLET_HTML_CLASS__", htmlClass)
      .replaceAll("__GOA_APPLET_CSP_NONCE__", this.escapeHtmlAttribute(nonce))
      .replaceAll("\"__GOA_APPLET_CODE_JSON__\"", codeLiteral);
    return { html, shellFound: true };
  }

  hasAppletShellTemplate() {
    return this.appletShellTemplate().length > 0;
  }

  appletShellTemplate() {
    const template = document.getElementById("goa-applet-shell-template");
    return template?.content?.textContent || "";
  }

  escapeHtmlAttribute(value) {
    return String(value)
      .replace(/&/g, "&amp;")
      .replace(/"/g, "&quot;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
  }

  prepareMissingShellContent(theme) {
    const dark = theme === "dark";
    const background = dark ? "#1c1917" : "#ffffff";
    const foreground = dark ? "#f5f5f4" : "#292524";

    return `
      <!DOCTYPE html>
      <html class="${dark ? "dark" : ""}" data-goa-applet-shell-error="missing-template">
        <head>
          <meta name="viewport" content="width=device-width,initial-scale=1">
          <style>
            html, body {
              min-height: 100%;
              margin: 0;
              background: ${background};
              color: ${foreground};
              font-family: "Inter", "Segoe UI", sans-serif;
            }
            body {
              display: grid;
              place-items: center;
              padding: 1rem;
            }
          </style>
        </head>
        <body>Unable to load applet shell.</body>
      </html>
    `;
  }

  archiveApplet(rawCode) {
    const title = prompt("Enter a name for this applet:");
    if (!title) return; // User cancelled

    if (!this.hasSaveFormTarget || !this.hasTitleInputTarget || !this.hasCodeInputTarget) {
      console.error("Save form elements not found in the executable block.");
      alert('Error: Unable to locate save form.');
      return;
    }
    this.titleInputTarget.value = title;
    this.codeInputTarget.value = rawCode;
    this.saveFormTarget.requestSubmit();
  }
}
