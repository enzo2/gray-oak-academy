import { Controller } from "@hotwired/stimulus"

/*
  This controller manages executable code blocks generated by the LLM.
  Blocks are intercepted by the customized markdown helper and duplicated into a syntax-highlighted block, and 
  a hidden pre block for raw code.
*/
export default class extends Controller {
  static targets = [
    "highlightedCode",
    "rawCode",
    "actionsContainer",
    "saveForm",
    "titleInput",
    "codeInput",
    "inlineOutput"
  ]
  static values = {
    renderTarget: String, // 'chalkboard' or 'inline'
    autoRun: Boolean,     // true or false
    hidden: Boolean       // true or false
  }

  connect() {
    //console.log("Code Executor connected", this.element);
    //console.log("Config:", this.renderTargetValue, this.autoRunValue, this.hiddenValue);

    const rawCode = this.rawCodeTarget.textContent;
    const actionsContainer = this.actionsContainerTarget;

    // Create and append buttons
    const toggleBtn = this.createToggleButton();
    actionsContainer.appendChild(toggleBtn);

    const runBtn = this.createRunButton(rawCode);
    actionsContainer.appendChild(runBtn);

    const archiveBtn = this.createArchiveButton(rawCode);
    actionsContainer.appendChild(archiveBtn);


    // Handle initial state
    if (this.hiddenValue) {
      this.highlightedCodeTarget.style.display = 'none';
      toggleBtn.textContent = "Show Code";
    } else {
      this.highlightedCodeTarget.style.display = 'block';
      toggleBtn.textContent = "Hide Code";
    }

    if (this.autoRunValue) {
      this.executeCode(rawCode, this.renderTargetValue, { manual: false, autoRun: true });
    }
  }

  _createButton(text, className, onClick) {
    const button = document.createElement("button");
    button.textContent = text;
    button.className = className;
    button.addEventListener("click", onClick);
    return button;
  }

  createToggleButton() {
    const btn = this._createButton(
      // Initial text is set in connect()
      "",
      "px-3 py-1 text-sm font-sans text-gray-900 dark:text-gray-100 bg-sky-200 dark:bg-sky-800 border border-sky-300 dark:border-sky-600 hover:border-sky-500 dark:hover:border-sky-400 rounded",
      () => {
        const isHidden = this.highlightedCodeTarget.style.display === 'none';
        this.highlightedCodeTarget.style.display = isHidden ? 'block' : 'none';
        btn.textContent = isHidden ? "Hide Code" : "Show Code";
      }
    );
    return btn;
  }

  createRunButton(rawCode) {
    return this._createButton(
      "Run",
      "px-3 py-1 ml-2 text-sm font-sans text-gray-900 dark:text-gray-100 bg-green-200 dark:bg-green-800 border border-green-300 dark:border-green-600 hover:border-green-500 dark:hover:border-green-400 rounded",
      () => this.executeCode(rawCode, this.renderTargetValue, { manual: true, autoRun: false })
    );
  }

  createArchiveButton(rawCode) {
    return this._createButton(
      "Save",
      "px-3 py-1 ml-2 text-sm font-sans text-gray-900 dark:text-gray-100 bg-stone-300 dark:bg-stone-700 border border-stone-400 dark:border-stone-500 hover:border-stone-600 dark:hover:border-stone-400 rounded",
      () => this.archiveApplet(rawCode)
    );
  }

  executeCode(rawCode, renderTarget, options = {}) {
    if (renderTarget === "chalkboard") {
      this.executeChalkboardCode(rawCode, options);
      return;
    }

    const output = this.getOutputElement(renderTarget);
    if (!output) return;

    output.innerHTML = ''; // Clear previous content
    output.style.display = 'block'; // Make sure output area is visible

    const iframe = this.createSandboxedIframe(renderTarget);
    output.appendChild(iframe);

    const iframeContent = this.prepareIframeContent(rawCode);
    iframe.srcdoc = iframeContent;
  }

  executeChalkboardCode(rawCode, _options = {}) {
    const iframeContent = this.prepareIframeContent(rawCode);
    const appletTitle = this.buildGeneratedAppletTitle();
    const appletKey = `jit_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
    this.dispatchChalkboardAppletRegistration({
      event_type: "register_applet",
      source: "jit",
      key: appletKey,
      applet_id: null,
      title: appletTitle,
      launch_url: null,
      embed_src: null,
      embed_srcdoc: iframeContent,
      shareable: false,
      share_url: null,
      focus: true,
      auto_open_in_board: true
    });
  }

  buildGeneratedAppletTitle() {
    const now = new Date();
    const time = now.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
    return `Generated Applet ${time}`;
  }

  dispatchChalkboardAppletRegistration(payload) {
    window.dispatchEvent(new CustomEvent("chalkboard:register-applet", { detail: payload }));
  }

  // Helper method to get the applet output element based on the render target
  getOutputElement(renderTarget) {
    if (!this.hasInlineOutputTarget) {
      console.error("Inline output element not found within code block wrapper.");
      return null;
    }
    const output = this.inlineOutputTarget;
    output.style.display = "block";
    output.innerHTML = ""; // Clear previous content
    return output;
  }

  createSandboxedIframe(renderTarget) {
    const iframe = document.createElement('iframe');
    iframe.sandbox = 'allow-scripts allow-modals allow-pointer-lock allow-popups allow-presentation allow-forms allow-downloads';
    iframe.allow = [
      'fullscreen',
      'accelerometer *',
      'encrypted-media *',
      'gyroscope *',
      'magnetometer *',
      'gamepad *',
      'midi *',
      'clipboard-write *',
      'local-fonts *',
      'xr-spatial-tracking *'
    ].join('; ');
    iframe.style.width = '100%';
    iframe.style.height = renderTarget === 'chalkboard' ? '100%' : '400px'; // Use 100% height for chalkboard
    iframe.style.border = '1px solid #ccc'; // Basic border
    iframe.style.backgroundColor = 'white'; // Ensure iframe bg is white for contrast
    return iframe;
  }

  // Basic HTML structure for the iframe content, including an importmap, and the code to be executed
  // Includes a simple console override to display logs/errors within the iframe
  prepareIframeContent(code) {

    // Escape any </script> tags in the code to prevent terminating the script early
    const codeLiteral = JSON.stringify(code).replace(/<\/script>/g, '<\\/script>');
    
    // Get the CSP nonce from the document head
    const meta = document.querySelector("meta[name='csp-nonce']");
    const nonce = meta ? meta.content : "";

    return `
      <!DOCTYPE html>
      <html>
      <head>
        <script src="https://cdn.jsdelivr.net/npm/@tailwindcss/browser@4" async></script>
        <style>
          @import url('https://fonts.googleapis.com/css2?family=Inter:ital,opsz,wght@0,14..32,100..900;1,14..32,100..900&family=Merriweather:ital,opsz,wght@0,18..144,300..900;1,18..144,300..900&display=swap');
          body { margin: 0; padding: 10px; font-family: "Inter", "Segoe UI", Optima, Futura, "Gill Sans MT", "Gill Sans", sans-serif; color: #333; }
          #sandbox { 
            min-height: 350px;
            max-height: 100%;
            overflow-y: auto;
            scrollbar-width: thin;
            scrollbar-color: rgba(156, 163, 175, 0.5) transparent;
          }
          /* Console styles */
          .console-log { 
            font-family: ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace; 
            margin: 4px 0;
            font-size: 0.8em;
            line-height: 1;
            word-break: break-word;
            white-space: pre-wrap;
          }
          .console-error { 
            color: #dc2626; 
            font-weight: 500;
            background: rgba(220, 38, 38, 0.1);
            padding: 4px 8px;
            border-radius: 4px;
          }
          .console-warn { 
            color: #d97706;
            background: rgba(217, 119, 6, 0.1);
            padding: 4px 8px;
            border-radius: 4px;
          }
          .console-info { 
            color: #2563eb;
            background: rgba(37, 99, 235, 0.1);
            padding: 4px 8px;
            border-radius: 4px;
          }
          .console-debug { 
            color: #6b7280;
          }
          .console-object { 
            background: #f3f4f6;
            padding: 8px;
            border-radius: 4px;
            white-space: pre-wrap;
            margin: 4px 0;
            border: 1px solid #e5e7eb;
          }
        </style>
        <style type="text/tailwindcss">      
          @theme { --font-sans: "InterVariable", sans-serif; --font-serif: "Merriweather", serif; }    
        </style>
        <script type="importmap" nonce="${nonce}">
          {
            "imports": {
              "react": "https://esm.sh/react",
              "react/": "https://esm.sh/react/",
              "react-dom/": "https://esm.sh/react-dom/",
              "p5": "https://esm.sh/p5?standalone",  
              "three": "https://esm.sh/three"
            }
          }
        </script>
        <script nonce="${nonce}">
          (function() {
            const createMemoryStorage = () => {
              let store = {};
              return {
                getItem(key) { return Object.prototype.hasOwnProperty.call(store, key) ? store[key] : null; },
                setItem(key, value) { store[key] = String(value); },
                removeItem(key) { delete store[key]; },
                clear() { store = {}; },
                key(index) { return Object.keys(store)[index] || null; },
                get length() { return Object.keys(store).length; }
              };
            };
            try {
              const testKey = "__storage_test__";
              window.localStorage.setItem(testKey, "1");
              window.localStorage.removeItem(testKey);
            } catch (e) {
              Object.defineProperty(window, "localStorage", { value: createMemoryStorage(), configurable: true });
            }
          })();
        </script>
        <script nonce="${nonce}">
          // Override console
          window.console = {
            _format: function(args, className) {
              const logElement = document.createElement('div');
              logElement.className = 'console-log ' + (className || '');
              
              args.forEach(arg => {
                if (arg instanceof Error) {
                  const errorDiv = document.createElement('div');
                  errorDiv.className = 'console-error';
                  errorDiv.textContent = arg.toString();
                  if (arg.stack) {
                    const stackDiv = document.createElement('pre');
                    stackDiv.className = 'console-debug';
                    stackDiv.textContent = arg.stack;
                    errorDiv.appendChild(stackDiv);
                  }
                  logElement.appendChild(errorDiv);
                } else if (typeof arg === 'object') {
                  try {
                    const objDiv = document.createElement('div');
                    objDiv.className = 'console-object';
                    objDiv.textContent = JSON.stringify(arg, null, 2);
                    logElement.appendChild(objDiv);
                  } catch (e) {
                    logElement.textContent += '[Circular Object]';
                  }
                } else {
                  const span = document.createElement('span');
                  span.textContent = String(arg) + ' ';
                  logElement.appendChild(span);
                }
              });
              
              // Wait for sandbox to be available
              const appendLog = () => {
                const sandbox = document.getElementById('sandbox');
                if (sandbox) {
                  sandbox.appendChild(logElement);
                } else {
                  // If sandbox not available yet, retry in 10ms
                  setTimeout(appendLog, 10);
                }
              };
              appendLog();
            },
            log: function(...args) {
              this._format(args);
            },
            error: function(...args) {
              this._format(args, 'console-error');
            },
            warn: function(...args) {
              this._format(args, 'console-warn');
            },
            info: function(...args) {
              //this._format(args, 'console-info');
            },
            debug: function(...args) {
              // Ignore debug logs.
            }
          };
        </script>
      </head>
      <body>
        <div id="sandbox"></div>
        <script type="module" nonce="${nonce}">
          const codeToExecute = ${codeLiteral};
          const blob = new Blob([codeToExecute], { type: 'text/javascript' });
          const moduleUrl = URL.createObjectURL(blob);

          import(moduleUrl).catch(error => {
            console.error(error);
          }).finally(() => {
            // Clean up the object URL to prevent memory leaks.
            URL.revokeObjectURL(moduleUrl);
          });
        </script>
      </body>
      </html>
    `;
  }

  archiveApplet(rawCode) {
    const title = prompt("Enter a name for this applet:");
    if (!title) return; // User cancelled

    if (!this.hasSaveFormTarget || !this.hasTitleInputTarget || !this.hasCodeInputTarget) {
      console.error("Save form elements not found in the executable block.");
      alert('Error: Unable to locate save form.');
      return;
    }
    this.titleInputTarget.value = title;
    this.codeInputTarget.value = rawCode;
    this.saveFormTarget.requestSubmit();
  }
}
